# Предложения с этими шаблонами вырезаются целиком (модель иногда обходит
# запреты в промпте, придумывая чуть иную формулировку «возникла ошибка...»).
_FORBIDDEN_SENTENCE_PATTERNS = [
    re.compile(r"[^.!?]*(?:возникл|произошл|случил|появил)\w*\s+(?:техническ\w*\s+)?ошибк\w*[^.!?]*[.!?]", re.IGNORECASE),
    re.compile(r"[^.!?]*техническ\w*\s+(?:ошибк\w*|проблем\w*|сбо\w*)[^.!?]*[.!?]", re.IGNORECASE),
    re.compile(r"[^.!?]*временно\s+не\s+оформ\w*[^.!?]*[.!?]", re.IGNORECASE),
    re.compile(r"[^.!?]*не\s+(?:получилось|удалось|получается)\s+оформ\w*[^.!?]*[.!?]", re.IGNORECASE),
    re.compile(r"[^.!?]*(?:обратитесь|свяжитесь|позвоните)\s+(?:на)?прямую[^.!?]*[.!?]", re.IGNORECASE),
    re.compile(r"[^.!?]*заявк\w*\s+(?:не\s+)?(?:оформлен\w*|обработан\w*)[^.!?]*[.!?]", re.IGNORECASE),
    re.compile(r"[^.!?]*ошибк\w*\s+при\s+регистрац\w*[^.!?]*[.!?]", re.IGNORECASE),
]

_GENERIC_HANDOFF_FALLBACK = (
    "Спасибо. Передаю вашу заявку нашему управляющему — она свяжется с вами в ближайшее время. Хорошего дня."
)


def sanitize_bot_outgoing(text: Optional[str]) -> str:
    """Убираем запрещённые формулировки и восклицательные знаки — модель иногда их игнорирует."""
    if not text:
        return ""
    t = text

    for pat in _FORBIDDEN_SENTENCE_PATTERNS:
        new_t = pat.sub(" ", t)
        if new_t != t:
            logger.warning(f"sanitize: вырезано предложение по шаблону {pat.pattern!r}")
            t = new_t

    t = re.sub(r"(?i)\bна\s+здоровье\b[!.,\s]*", "Пожалуйста. ", t)
    t = t.replace("!", ".")
    t = re.sub(r"\.{3,}", ".", t)
    t = re.sub(r"\s+", " ", t).strip()

    # Если после фильтрации осталась пустая/обрезанная заглушка — даём безопасный fallback.
    if not t or len(t) < 15:
        logger.warning("sanitize: после фильтрации текст слишком короткий, отдаю generic handoff")
        t = _GENERIC_HANDOFF_FALLBACK

    return t


