# ошибку» и «обратитесь напрямую» — это запрещено промптом и звучит как «бот сломан»).
_DIALOG_ERROR_FALLBACK = (
    "Секунду, пожалуйста. Напишите, пожалуйста, ваш вопрос ещё раз — я обязательно помогу."
)

