def _normalize_begin_time(time_str: str) -> str:
    """10:00:00 → 10:00; пустое → пустое."""
    time_str = (time_str or "").strip()
    if not time_str:
        return ""
    match = re.match(r"^(\d{1,2}):(\d{2})", time_str)
    if match:
        return f"{int(match.group(1)):02d}:{match.group(2)}"
    return time_str


def _parse_schedule_date(date_str: str) -> Optional[date]:
    date_str = (date_str or "").strip()
    if not date_str:
        return None
    for fmt in ("%Y-%m-%d", "%d.%m.%Y", "%d/%m/%Y"):
        try:
            return datetime.strptime(date_str, fmt).date()
        except ValueError:
            continue
    return None


def _format_schedule_date(date_str: str) -> str:
    """2026-06-22 → 22.06.2026; нераспознанное — как есть."""
    parsed = _parse_schedule_date(date_str)
    if parsed:
        return parsed.strftime("%d.%m.%Y")
    return (date_str or "").strip()


def _minutes_until_lesson(obj: dict) -> Optional[int]:
    """Минуты до начала занятия по date+beginTime в школьном TZ; None — не удалось вычислить."""
    date_str = (obj.get("date") or obj.get("beginDate") or "").strip()
    time_str = _normalize_begin_time(obj.get("beginTime") or "")
    parsed_date = _parse_schedule_date(date_str)
    if parsed_date is None or not time_str:
        return None
    try:
        scheduled = datetime.strptime(
            f"{parsed_date.isoformat()} {time_str}", "%Y-%m-%d %H:%M"
        )
        now_local = datetime.now(_SCHOOL_TZ).replace(tzinfo=None)
        return int((scheduled - now_local).total_seconds() // 60)
    except ValueError:
        return None


_EMPLOYEE_FIVE_MIN_THRESHOLD = 20  # ≤20 мин до урока → «через 5 минут», иначе «через 1 час»


def _employee_lesson_start_reminder_text(event: str, obj: dict) -> Optional[str]:
    """Текст напоминания преподавателю: за 1 час или за 5 минут (+ ссылка отдельно).

    MoyKlass часто шлёт одно и то же событие lesson_start и за час, и за 5 минут —
    выбираем шаблон по фактическому времени до beginTime, а не только по event.
    """
    if event not in ("lesson_start", "lesson_start_hours"):
        return None

    minutes_left = _minutes_until_lesson(obj)
    if minutes_left is not None:
        if minutes_left <= _EMPLOYEE_FIVE_MIN_THRESHOLD:
            return "Напоминаем о начале урока через 5 минут."
        return "Напоминаем о начале урока через 1 час."

    # Нет date/beginTime — fallback по типу события (редко, после enrich).
    if event == "lesson_start_hours":
        return "Напоминаем о начале урока через 1 час."
    return "Напоминаем о начале урока через 5 минут."


def _scheduled_event_is_past(obj: dict, event: Optional[str] = None) -> bool:
    """True — напоминание уже в прошлом или время не удалось определить (fail-closed)."""
    date_str = (obj.get("date") or obj.get("beginDate") or "").strip()
    time_str = _normalize_begin_time(obj.get("beginTime") or "")
    today = datetime.now(_SCHOOL_TZ).date()
    now_local = datetime.now(_SCHOOL_TZ).replace(tzinfo=None)

    if not date_str:
        if event == "class_start_hours":
            # Это событие по определению «сегодня» — даты в payload нет.
            # Берём beginTime из enrich (GET /classes/{id}); без него — fail-closed.
            if not time_str:
                return True
            try:
                scheduled = datetime.strptime(
                    f"{today.isoformat()} {time_str}", "%Y-%m-%d %H:%M"
                )
                return scheduled < now_local
            except ValueError:
                return True
        # lesson_start / lesson_start_hours без даты — не отправляем (fail-closed).
        return event in _TODAY_LESSON_EVENTS

    parsed_date = _parse_schedule_date(date_str)
    if parsed_date is None:
        return True

    if parsed_date < today:
        return True
    if parsed_date > today:
        return False

    # Дата — сегодня
    if event in {"lesson_start_days", "class_start_days"}:
        return False

    if not time_str:
        # Раньше подставляли 23:59 → пропускали весь день; для «сегодня в 10:00» это опасно.
        return event in _TODAY_LESSON_EVENTS

    try:
        scheduled = datetime.strptime(f"{parsed_date.isoformat()} {time_str}", "%Y-%m-%d %H:%M")
        return scheduled < now_local
    except ValueError:
        return True


def _should_skip_stale_client_webhook(data: dict, event: str, obj: dict) -> bool:
    """Пропустить старые/ретраи вебхуков — только события с момента деплоя и будущие напоминания."""
    if MOYKLASS_WEBHOOK_ENABLED_SINCE is not None:
        event_time = data.get("time")
        if event_time is not None:
            try:
                if int(event_time) < MOYKLASS_WEBHOOK_ENABLED_SINCE:
                    return True
            except (TypeError, ValueError):
                pass

    if event in _SCHEDULED_REMINDER_EVENTS and _scheduled_event_is_past(obj, event):
        return True

    # lesson_changed по прошедшей/без даты — пропуск (анти-спам исторического backfill).
    if event == "lesson_changed":
        lesson_date = _parse_schedule_date(obj.get("date") or obj.get("beginDate") or "")
        if lesson_date is None or lesson_date < datetime.now(_SCHOOL_TZ).date():
            return True

    return False


def _apply_webhook_test_phone_override(phones: List[str], log_prefix: str) -> List[str]:
    if not _webhook_test_mode_active():
        return phones
    logger.warning(
        "%s: ТЕСТОВЫЙ РЕЖИМ — вместо %s отправляем только на %s",
        log_prefix,
        phones,
        MOYKLASS_WEBHOOK_TEST_PHONE,
    )
    return [MOYKLASS_WEBHOOK_TEST_PHONE]


async def _dispatch_moyklass_webhook(
    log_prefix: str,
    event: Optional[str],
    obj: dict,
    message: Optional[str],
    phones: List[str],
    record_history: bool,
) -> dict:
    if not message:
        logger.info("%s: event=%s: нет шаблона, пропускаем", log_prefix, event)
        return {"status": "ok"}

    if not phones:
        logger.warning("%s: event=%s: телефон не найден", log_prefix, event)
        return {"status": "ok"}

    test_mode = _webhook_test_mode_active()
    phones = _apply_webhook_test_phone_override(phones, log_prefix)
    if test_mode:
        message = f"[ТЕСТ CRM] {message}"
        record_history = False

    logger.info("%s: event=%s получатели=%s", log_prefix, event, phones)

    user_id = obj.get("userId")
    for phone in phones:
        dedup_key = _crm_dedup_key(event, user_id, phone, obj)
        if dedup_key and _crm_already_sent(dedup_key):
            logger.info(
                "%s: event=%s userId=%s phone=%s — уже отправляли сегодня, пропуск (dedup)",
                log_prefix, event, user_id, phone,
            )
            continue

        chat_id = phone_to_chat_id(phone)
        if not chat_id:
            logger.warning("%s: не удалось нормализовать телефон %r", log_prefix, phone)
            continue
        try:
            delivered = await send_whatsapp(chat_id, message)
            if not delivered:
                logger.error("%s: НЕ доставлено %s (см. send_whatsapp выше)", log_prefix, chat_id)
                continue
            if dedup_key:
                _mark_crm_sent(dedup_key)
            if record_history:
                record_crm_notification_in_history(chat_id, message)
            logger.info("%s: отправлено %s", log_prefix, chat_id)
        except Exception as e:
            logger.error("%s: ошибка отправки %s: %s", log_prefix, chat_id, e)

    return {"status": "ok"}


