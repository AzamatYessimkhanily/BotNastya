async def process_dialog(chat_id):
    async with _dialog_lock(chat_id):
        buffer = message_buffers.pop(chat_id, None)
        if not buffer:
            return
        user_text = " ".join(buffer["messages"])
        logger.info(f"Обработка для {chat_id}: {user_text}")

        current_time = time.time()
        if chat_id in last_activity:
            if current_time - last_activity[chat_id] > SESSION_TIMEOUT:
                logger.info(f"Сброс памяти для {chat_id}")
                chat_history.pop(chat_id, None)
                known_users.pop(chat_id, None)
                client_dossiers.pop(chat_id, None)
                handoff_completed.pop(chat_id, None)
        last_activity[chat_id] = current_time

        if chat_id not in chat_history:
            chat_history[chat_id] = [{"role": "system", "content": SYSTEM_PROMPT}]

            current_phone = chat_id.split("@")[0]
            chat_history[chat_id].append({
                "role": "system",
                "content": (
                    f"[ТЕЛЕФОН КЛИЕНТА]: {current_phone}. Чат в WhatsApp — номер уже есть. "
                    f"Для заявки в CRM используй этот номер; не проси продиктовать телефон для связи здесь, "
                    f"если клиент сам не попросил указать другой."
                )
            })

            if chat_id not in known_users:
                phone = chat_id.split("@")[0]
                found = await crm.find_user_smart(phone)

                if found:
                    user_obj = found["user"]
                    dossier = found["dossier"]
                    known_users[chat_id] = user_obj
                    client_dossiers[chat_id] = dossier

                    mgr_contact = ""
                    if dossier["filial_id"] and dossier["filial_id"] in BRANCH_PHONES:
                        mgr_contact = f"Его менеджер: {BRANCH_PHONES[dossier['filial_id']]}."

                    inject_msg = (
                        f"[СИСТЕМНОЕ ДОСЬЕ КЛИЕНТА]\n"
                        f"Имя: {dossier['name']}\n"
                        f"Группы: {dossier['groups']}\n"
                        f"Ближайшие уроки: {dossier['schedule']}\n"
                        f"Баланс: {dossier['balance']}\n"
                        f"{mgr_contact}\n"
                        f"ИНСТРУКЦИЯ: Это действующий ученик! НЕ СПРАШИВАЙ ИМЯ И ТЕЛЕФОН.\n"
                        f"1. Поздоровайся по имени.\n"
                        f"2. Если есть урок в поле 'Ближайшие уроки', ОБЯЗАТЕЛЬНО скажи: 'Ждем вас [Дата/Время] на уроке с [Имя преподавателя]'.\n"
                        f"3. Если нет — спроси, чем помочь.\n"
                        f"4. Если вопрос сложный, дай номер менеджера филиала."
                    )
                    chat_history[chat_id].append({"role": "system", "content": inject_msg})
                    logger.info(f"Загружено досье: {dossier['name']}")

        user_payload = (
            "[ОПРЕДЕЛИ ЯЗЫК ЭТОГО СООБЩЕНИЯ КЛИЕНТА САМОСТОЯТЕЛЬНО "
            "И ОТВЕТЬ НА ЭТОМ ЖЕ ЯЗЫКЕ. ЕСЛИ КЛИЕНТ ПРОСИТ КОНКРЕТНЫЙ ЯЗЫК — "
            "СРАЗУ ПЕРЕКЛЮЧИСЬ НА НЕГО.]\n"
            f"{user_text}"
        )

        if chat_id in handoff_completed:
            if _is_pure_acknowledgment(user_text):
                logger.info(f"post-handoff ack для {chat_id}: {user_text!r}")
                chat_history[chat_id].append({"role": "user", "content": user_payload})
                ack_reply = _post_handoff_ack_reply(user_text)
                chat_history[chat_id].append({"role": "assistant", "content": ack_reply})
                await send_whatsapp(chat_id, ack_reply, sanitize_fallback="short")
                return
            logger.info(f"post-handoff: новый вопрос от {chat_id}, снимаем флаг handoff")
            handoff_completed.pop(chat_id, None)

        chat_history[chat_id].append({"role": "user", "content": user_payload})

        # План авто-реактивации: клиент написал — (пере)ставим таймер напоминаний.
        _update_followup_tracking(chat_id, user_text)

        # Детерминированная защита от зацикливания на имени: если бот уже спрашивал имя,
        # вставляем жёсткую директиву — переспрашивать нельзя, надо оформлять заявку.
        _already_asked_name = any(
            isinstance(m, dict) and m.get("role") == "assistant"
            and isinstance(m.get("content"), str) and _NAME_ASK_RE.search(m["content"])
            for m in chat_history[chat_id]
        )
        _name_guard_present = any(
            isinstance(m, dict) and m.get("role") == "system"
            and m.get("content") == _NAME_GUARD_DIRECTIVE
            for m in chat_history[chat_id]
        )
        if _already_asked_name and not _name_guard_present:
            chat_history[chat_id].append({"role": "system", "content": _NAME_GUARD_DIRECTIVE})

        try:
            response = await openai_client.chat.completions.create(
                model=OPENAI_MODEL,
                messages=chat_history[chat_id],
                tools=tools,
                tool_choice="auto",
                temperature=0.5
            )
            msg = response.choices[0].message
            lead_registered_this_turn = False

            if msg.tool_calls:
                chat_history[chat_id].append(msg)
                # КАЖДЫЙ tool_call ОБЯЗАН получить парный ответ role:"tool" — иначе
                # история становится невалидной и все следующие запросы к OpenAI
                # падают 400 (диалог клиента залипает на fallback). Поэтому ответ
                # гарантируем даже при битых аргументах / неожиданном сбое create_lead.
                for tool in msg.tool_calls:
                    try:
                        args = json.loads(tool.function.arguments)
                    except (json.JSONDecodeError, TypeError, ValueError) as e:
                        logger.error(
                            f"CRM вызов: не удалось распарсить аргументы "
                            f"{tool.function.arguments!r}: {e}"
                        )
                        args = {}
                    # Валидный JSON может оказаться не object (null / [] / число) —
                    # тогда args.get(...) упал бы AttributeError и сорвал гарантию
                    # tool-ответа. Приводим к пустому dict.
                    if not isinstance(args, dict):
                        logger.error("CRM вызов: аргументы не object: %r", args)
                        args = {}
                    logger.info(f"CRM вызов: {args}")

                    if tool.function.name == "register_client_request":
                        lead_registered_this_turn = True
                        phone_to_save = args.get("client_phone")
                        if not phone_to_save or "не указа" in phone_to_save.lower():
                            phone_to_save = chat_id.split("@")[0]
                        try:
                            result_text = await crm.create_lead(
                                name=args.get("client_name", "Клиент"),
                                phone=phone_to_save,
                                age=args.get("client_age", "-"),
                                experience=args.get("experience", "-"),
                                preference=args.get("preference", "Не выбрано")
                            )
                        except Exception as e:
                            logger.error(f"create_lead неожиданно упал: {e}")
                            mgr_name, mgr_phone = crm._pick_manager_info("default", None)
                            result_text = crm._handoff_message(mgr_name, mgr_phone, success=False)
                    elif tool.function.name == "request_manager_callback":
                        dossier = client_dossiers.get(chat_id) or {}
                        client_phone = chat_id.split("@")[0]
                        client_name = dossier.get("name") or "Клиент"
                        filial_id = dossier.get("filial_id")
                        try:
                            result_text = await crm.notify_client_callback_request(
                                client_name=client_name,
                                client_phone=client_phone,
                                filial_id=filial_id,
                                reason=args.get("reason", ""),
                            )
                        except Exception as e:
                            logger.error(f"request_manager_callback неожиданно упал: {e}")
                            mgr_name, mgr_phone = crm._pick_manager_info(filial_id, None)
                            result_text = (
                                "СИСТЕМНОЕ СООБЩЕНИЕ: ЗАПРОС НА СВЯЗЬ ЗАФИКСИРОВАН.\n"
                                f"MGR_NAME={mgr_name}\n"
                                f"MGR_PHONE={mgr_phone}\n"
                                "ИНСТРУКЦИЯ: подтверди клиенту, что управляющий свяжется в ближайшее время."
                            )
                    else:
                        logger.warning(
                            f"Неизвестный tool-call {tool.function.name!r} — отвечаю нейтрально"
                        )
                        result_text = "СИСТЕМНОЕ СООБЩЕНИЕ: функция не поддерживается."

                    chat_history[chat_id].append({
                        "tool_call_id": tool.id,
                        "role": "tool",
                        "name": tool.function.name,
                        "content": result_text
                    })

                final = await openai_client.chat.completions.create(
                    model=OPENAI_MODEL, messages=chat_history[chat_id]
                )
                bot_answer = final.choices[0].message.content
            else:
                bot_answer = msg.content

            sanitized_answer = sanitize_bot_outgoing(bot_answer)
            if lead_registered_this_turn or _is_handoff_message(sanitized_answer):
                _mark_handoff_completed(chat_id)
            chat_history[chat_id].append({"role": "assistant", "content": sanitized_answer})
            await send_whatsapp(chat_id, sanitized_answer)

        except Exception as e:
            logger.error(f"Ошибка AI: {e}")
            # Чиним историю, если упали посреди tool-call (иначе все следующие
            # запросы к OpenAI будут падать 400 и диалог залипнет на fallback).
            _repair_dangling_tool_calls(chat_id)
            try:
                await send_whatsapp(chat_id, _DIALOG_ERROR_FALLBACK)
            except Exception as send_err:
                logger.error(f"Не удалось отправить fallback: {send_err}")

