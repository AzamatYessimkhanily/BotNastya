def _bare_client_text(text: str) -> str:
    """Текст клиента без служебных обёрток webhook/буфера."""
    t = (text or "").strip()
    if "[CLIENT_MESSAGE]:" in t:
        t = t.split("[CLIENT_MESSAGE]:", 1)[-1].strip()
    if t.lower().startswith("[голосовое]:"):
        t = t.split(":", 1)[-1].strip()
    return t.strip()


def _normalize_ack_phrase(text: str) -> str:
    return re.sub(r"[^\w\s]", " ", text.lower(), flags=re.UNICODE).strip()


def _is_pure_acknowledgment(text: str) -> bool:
    """Короткое согласие/благодарность после закрытия диалога — не новый вопрос."""
    bare = _bare_client_text(text)
    if not bare:
        return False
    low = bare.lower()
    if any(hint in low for hint in _SUBSTANTIVE_FOLLOWUP_HINTS):
        return False
    normalized = _normalize_ack_phrase(bare)
    return normalized in _PURE_ACK_PHRASES


def _is_handoff_message(text: str) -> bool:
    low = (text or "").lower()
    return any(marker in low for marker in _HANDOFF_MARKERS)


def _post_handoff_ack_reply(user_text: str) -> str:
    if _KAZAKH_CHAR_RE.search(_bare_client_text(user_text)):
        return "Рақмет. Басқарушы жақын арада сізбен хабарласады."
    return _SHORT_SANITIZE_FALLBACK


def _history_message_content(message) -> str:
    """Текст элемента истории. Элемент может быть dict ИЛИ объектом OpenAI
    (ChatCompletionMessage кладётся в историю при tool-call) — у объекта нет
    .get(), поэтому достаём content универсально, чтобы не падать с AttributeError."""
    if isinstance(message, dict):
        return message.get("content") or ""
    return getattr(message, "content", None) or ""


def _message_tool_call_ids(message) -> List[str]:
    """tool_call id из элемента истории (dict или объект OpenAI)."""
    if isinstance(message, dict):
        tool_calls = message.get("tool_calls") or []
    else:
        tool_calls = getattr(message, "tool_calls", None) or []
    ids: List[str] = []
    for tc in tool_calls:
        tid = tc.get("id") if isinstance(tc, dict) else getattr(tc, "id", None)
        if tid:
            ids.append(tid)
    return ids


def _repair_dangling_tool_calls(chat_id: str) -> None:
    """Снимает «осиротевший» assistant-tool_call из истории.

    Если в истории остался assistant с tool_calls, на которые НЕ записаны парные
    ответы role:"tool", OpenAI отвечает 400 на КАЖДЫЙ следующий запрос — диалог
    клиента залипает на аварийном fallback до сброса сессии. Эта функция удаляет
    такой висячий хвост, восстанавливая валидность истории.
    """
    history = chat_history.get(chat_id)
    if not history:
        return
    while history:
        idx = next(
            (i for i in range(len(history) - 1, -1, -1) if _message_tool_call_ids(history[i])),
            None,
        )
        if idx is None:
            return
        expected = set(_message_tool_call_ids(history[idx]))
        answered = {
            m.get("tool_call_id")
            for m in history[idx + 1:]
            if isinstance(m, dict) and m.get("role") == "tool" and m.get("tool_call_id")
        }
        if expected <= answered:
            return  # все tool_calls закрыты — история валидна
        # Удаляем только сломанную группу: assistant с tool_calls и идущие
        # сразу за ним частичные ответы role:"tool". Хвост после группы (например,
        # свежее сообщение клиента текущего хода) сохраняем.
        end = idx + 1
        while (
            end < len(history)
            and isinstance(history[end], dict)
            and history[end].get("role") == "tool"
        ):
            end += 1
        logger.warning(
            "repair: удаляю висячий tool_call в истории %s (ожидалось %s, отвечено %s)",
            chat_id, expected, answered,
        )
        del history[idx:end]


def _mark_handoff_completed(chat_id: str) -> None:
    handoff_completed[chat_id] = time.time()
    # Заявка передана управляющему = логическое завершение → снимаем с реактивации.
    followups.pop(chat_id, None)
    if chat_id not in chat_history:
        return
    recent = chat_history[chat_id][-4:]
    if any("ЗАЯВКА УЖЕ ПЕРЕДАНА" in _history_message_content(m) for m in recent):
        return
    chat_history[chat_id].append({
        "role": "system",
        "content": (
            "[ЗАЯВКА УЖЕ ПЕРЕДАНА]: Управляющему уже передали заявку этого клиента. "
            "На короткие реакции (хорошо, ок, спасибо, до свидания) ответь одной короткой "
            "фразой благодарности — НЕ повторяй передачу заявки и не вызывай register_client_request снова. "
            "Если клиент задаёт новый вопрос — отвечай по существу."
        ),
    })


def _update_followup_tracking(chat_id: str, user_text: str) -> None:
    """Обновляет план авто-реактивации по входящему сообщению клиента.

    Ставит/сбрасывает таймер напоминания. Действующих учеников (есть досье) и тех,
    кто явно отказался, снимаем — им реактивация не нужна. Запись = логическое
    завершение обрабатывается отдельно в _mark_handoff_completed.
    """
    if not FOLLOWUP_ENABLED:
        return
    # Действующий ученик — «так и не записались» к нему неприменимо.
    if chat_id in known_users:
        followups.pop(chat_id, None)
        return
    if _FOLLOWUP_REFUSAL_RE.search(user_text or ""):
        if chat_id in followups:
            logger.info("followup: %s — клиент отказался, снимаем с реактивации", chat_id)
        followups.pop(chat_id, None)
        return
    # Клиент активен: (пере)ставим таймер, цепочку напоминаний начинаем заново.
    followups[chat_id] = {"last_client_ts": time.time(), "stage": 0}


def sanitize_bot_outgoing(text: Optional[str], *, fallback: str = "handoff") -> str:
    """Убираем запрещённые формулировки и восклицательные знаки — модель иногда их игнорирует."""
    if not text:
        return ""
    t = text

    for pat in _FORBIDDEN_SENTENCE_PATTERNS:
        new_t = pat.sub(" ", t)
        if new_t != t:
            logger.warning(f"sanitize: вырезано предложение по шаблону {pat.pattern!r}")
            t = new_t

    t = re.sub(r"(?i)\bна\s+здоровье\b[!.,\s]*", "Пожалуйста. ", t)
    t = t.replace("!", ".")
    t = re.sub(r"\.{3,}", ".", t)
    t = re.sub(r"\s+", " ", t).strip()

    if not t or len(t) < 15:
        if fallback == "short":
            logger.warning("sanitize: короткий ответ после handoff, отдаю short fallback")
            t = _SHORT_SANITIZE_FALLBACK
        else:
            logger.warning("sanitize: после фильтрации текст слишком короткий, отдаю generic handoff")
            t = _GENERIC_HANDOFF_FALLBACK

    return t


async def send_whatsapp(chat_id, text, *, sanitize_fallback: str = "handoff", sanitize: bool = True) -> bool:
    # Доп. нормализация на случай прямых вызовов (голосовые ошибки и т.д.).
    # sanitize=False — для служебных сообщений сотрудникам (сохраняем формат/переносы).
    # Возвращает True только при подтверждённой отправке (Green API отдал idMessage).
    if sanitize:
        text = sanitize_bot_outgoing(text, fallback=sanitize_fallback)
    url = f"https://api.green-api.com/waInstance{GREEN_API_ID}/sendMessage/{GREEN_API_TOKEN}"
    try:
        async with httpx.AsyncClient(timeout=30.0) as client:
            resp = await client.post(url, json={"chatId": chat_id, "message": text})
    except Exception as e:
        logger.error("send_whatsapp: сетевая ошибка при отправке %s: %s", chat_id, e)
        return False

    if resp.status_code != 200:
        logger.error(
            "send_whatsapp: Green API %s -> %s %s",
            chat_id, resp.status_code, (resp.text or "")[:300],
        )
        return False

    # При успехе Green API возвращает {"idMessage": "..."}; его отсутствие = не доставлено.
    try:
        body = resp.json()
    except Exception:
        body = None
    if not (isinstance(body, dict) and body.get("idMessage")):
        logger.warning(
            "send_whatsapp: ответ без idMessage %s -> %s",
            chat_id, (resp.text or "")[:200],
        )
        return False
    return True

