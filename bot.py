def phone_to_chat_id(phone: str) -> Optional[str]:
    clean = re.sub(r"[^\d]", "", phone or "")
    if len(clean) == 10:
        clean = "7" + clean
    elif len(clean) == 11 and clean[0] == "8":
        clean = "7" + clean[1:]
    if len(clean) < 11:
        return None
    return f"{clean}@c.us"


